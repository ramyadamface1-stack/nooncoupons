// Render exact existing canonical R2 rescue XML routes as Static Assets.
// Executes production rescueSitemapResponse(), not a duplicated renderer:
// preserves URL structure, country coupon, encoded image kw, and
// Arabic/English catalog pagination byte-for-byte as source behavior.
// Fake env can only READ CI-local R2 JSON snapshots; no R2/API writes possible.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {rescueSitemapResponse} from '../r2-emergency-readonly.js';

const temp=resolve(process.cwd(),'.ndn-rescue-temp');
const out=resolve(process.cwd(),'.ndn-static-assets');
const cap=600;
const source=JSON.parse(await readFile(join(temp,'index.json'),'utf8'));
const paths=source.paths,inputs=source.inputs;
const fail=message=>{throw Error('NDN_STATIC_RESCUE_'+message)};
if(!Array.isArray(paths)||!paths.length||paths.length>cap||!inputs||typeof inputs!=='object')fail('UNSAFE_STAGING');
if(new Set(paths).size!==paths.length)fail('DUPLICATE_REFERENCES');
const matcher=/^\/sitemap-rescue-(?:(?:articles|images|english|english-images)-(?:0|[1-9]\d{0,3})|(?:catalog|english-catalog))\.xml$/;
if(paths.some(path=>!matcher.test(path)))fail('UNEXPECTED_PUBLIC_SITEMAP_PATH');
for(const filename of Object.values(inputs))
 if(!/^segment-\d{4}\.json$/.test(String(filename)))fail('UNSAFE_STAGED_SEGMENT_PATH');
const manifestBody=await readFile(join(temp,'manifest.json'),'utf8');
const env={
 CONTENT_FINAL:{
   get:async key=>{
     if(key==='seo-rescue/index.json')return {text:async()=>manifestBody};
     if(!Object.prototype.hasOwnProperty.call(inputs,key))return null;
     const filename=inputs[key];
     return {text:async()=>readFile(join(temp,filename),'utf8')};
   }
 }
};
await mkdir(out,{recursive:true});
let allEntries=0,images=0,english=0,catalog=0,bytes=0;
for(const path of paths){
 const response=await rescueSitemapResponse(path,env);
 if(!response||response.status!==200)fail('CANONICAL_RENDER_UNAVAILABLE_'+path+'_'+response?.status);
 const xml=await response.text();
 if(!xml.startsWith('<?xml version="1.0" encoding="UTF-8"?>')||!xml.includes('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"')||!xml.endsWith('</urlset>'))
   fail('CANONICAL_RENDER_XML_INVALID_'+path);
 if(xml.includes('<!DOCTYPE')||xml.includes('<script'))fail('UNSAFE_XML_MARKUP_'+path);
 const rows=[...xml.matchAll(/<loc>([^<]+)<\/loc>/g)];
 if(rows.length===0||rows.length>15000)fail('EMPTY_OR_EXCESSIVE_CANONICAL_XML_'+path);
 // XML URLs always first-party; in image XML this includes image:loc values
 // generated by the original renderer, including exact coupon and kw.
 if(rows.some(m=>!m[1].startsWith('https://noondealsnow.com/')))fail('CROSS_DOMAIN_XML_URL_'+path);
 const dataBytes=Buffer.byteLength(xml,'utf8');
 if(dataBytes>20_000_000)fail('WORKERS_FREE_STATIC_ASSET_TOO_LARGE_'+path);
 bytes+=dataBytes;
 if(/-images-\d+\.xml$/.test(path))images++;
 else if(/-english-\d+\.xml$/.test(path))english++;
 else if(/-catalog\.xml$/.test(path))catalog++;
 allEntries+=rows.length;
 await writeFile(join(out,path.slice(1)),xml,'utf8');
}
console.log('NDN_STATIC_RESCUE_SITEMAPS=BUILT;CANONICAL_XML_FILES='+paths.length+
 ';XML_LOC_ELEMENTS='+allEntries+';ENGLISH_NONIMAGE_SHARDS='+english+
 ';IMAGE_SHARDS='+images+';CATALOGS='+catalog+';BYTES='+bytes);
console.log('NDN_STATIC_RESCUE_SOURCE=EXACT_EXISTING_PRODUCTION_RESCUE_SITEMAP_RENDERER;R2_WRITES=ZERO;ARTICLE_HTML_CHANGES=ZERO;NO_NEW_PROVIDER_KEYS=true');
